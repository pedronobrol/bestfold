// Writes public/island-worker.js, the self-contained Web Worker the hosted app starts for the
// volunteer search (see viewer/island-worker.js).
import { writeFileSync } from 'node:fs';
import { workerBundle } from './bundle.js';

const src = `// Generated by scripts/build-worker.js from src/ and viewer/island-worker.js. Do not edit.\n${workerBundle()}`;
writeFileSync(new URL('../public/island-worker.js', import.meta.url), src);
console.log(`public/island-worker.js  ${(src.length / 1024).toFixed(0)} KB`);
