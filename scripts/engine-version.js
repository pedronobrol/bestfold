// Writes src/version.js: a short hash of the engine source. Results from different engine
// versions are never mixed (the shared board, the browser islands and the server all check it).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const dir = new URL('../src/', import.meta.url);
const h = createHash('sha256');
for (const f of readdirSync(dir).filter((f) => f.endsWith('.js') && f !== 'version.js').sort()) h.update(f).update(readFileSync(new URL(f, dir)));
const v = h.digest('hex').slice(0, 12);
writeFileSync(new URL('version.js', dir), `// Generated by scripts/engine-version.js. Do not edit.\nexport const ENGINE_VERSION = '${v}';\n`);
console.log('engine version', v);
